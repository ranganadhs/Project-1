/**
 * Fingerprint inputs — what is allowed to change `runtimeVersion`.
 *
 * `app.config.ts` sets `runtimeVersion: { policy: 'fingerprint' }`, so this
 * file decides which over-the-air updates can reach which binaries.
 *
 * ── WHY `ExpoConfigExtraSection` IS SKIPPED ───────────────────────────────
 *
 * `app.config.ts` carries `extra.updatePolicy` and `extra.otaBuild`, both set
 * per publish from environment variables, so a running bundle can read the NEXT
 * bundle's manifest and decide whether to restart the app. See src/lib/updates.
 *
 * `extra` is a fingerprint input by DEFAULT. Without this skip, choosing a
 * policy changes the runtime version, and the update publishes to a runtime
 * version no build has — it succeeds, it is billed, and it reaches nobody.
 * There is no error, because nothing is wrong: the update is simply for a
 * different app than the one installed. With the skip, every policy value
 * produces the same runtime version; without it, each produces its own.
 *
 * DELETING THIS FILE SILENTLY BREAKS EVERY FORCED UPDATE, and every OTA build
 * number with it. Guarded by src/lib/updates/updates.test.ts, which is the only
 * thing that can see it — typecheck, lint, the bundler and `expo export` are
 * all identically green either way.
 *
 * ── WHY NOTHING ELSE IS SKIPPED ───────────────────────────────────────────
 *
 * `PackageJsonScriptsAll` is deliberately NOT set. A script change usually does
 * not affect the native build, but it can — `expo run:*` flags, a postinstall
 * patch — and the default already skips the android/ios scripts that do not
 * contain `run`. Losing that signal to save an occasional rebuild is the wrong
 * side of the trade.
 *
 * Native `ios/` and `android/` need no skip. The native projects are generated (both are
 * gitignored and regenerated by prebuild), so @expo/fingerprint resolves the
 * workflow as `managed` and already ignores their contents — the source entry
 * it emits carries `hash: null` and the reason `bareNativeDir`. Note that
 * `eas fingerprint:compare` still PRINTS `new directory: ios` when comparing a
 * machine that has run `expo run:ios` against a build that has not. That line
 * is cosmetic and is not why two fingerprints differ; look further up the diff.
 *
 * @type {import('@expo/fingerprint').Config}
 */
module.exports = {
  sourceSkips: ['ExpoConfigExtraSection'],
};
